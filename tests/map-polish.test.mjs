import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const main=readFileSync(join(root,'src/main.js'),'utf8');
const data=readFileSync(join(root,'src/data.js'),'utf8');
assert.match(main,/drawJungleDistrict\(0\);drawJungleDistrict\(1\);/);
assert.match(main,/for\(const \[i,b\] of BUILDINGS\.entries\(\)\)drawBuilding\(b,i\)/);
assert.match(main,/for\(const c of JUNGLE_COVER\)drawCover\(c\)/);
assert.match(main,/for\(const feature of JUNGLE_LANDMARKS\)drawJungleLandmark\(feature\)/);
assert.match(main,/routeStroke\(/);
assert.match(data,/JUNGLE_LOOP_CROSSINGS/);
assert.match(data,/jungleTrailY/);
console.log('✓ Boston map, two large jungles, road curves and gameplay collision visuals retained');
