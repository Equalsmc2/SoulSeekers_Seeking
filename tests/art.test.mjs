import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const main=readFileSync(join(root,'src/main.js'),'utf8');
const html=readFileSync(join(root,'index.html'),'utf8');
assert.match(html,/R03\.5/);
assert.match(main,/function drawWorld\(\)/);
assert.match(main,/function drawJungleDistrict\(/);
assert.match(main,/for\(const \[i,b\] of BUILDINGS\.entries\(\)\)drawBuilding\(b,i\)/);
assert.match(main,/for\(const c of JUNGLE_COVER\)drawCover\(c\)/);
assert.match(main,/for\(const car of STREET_COVER\)drawStreetCover\(car\)/);
assert.doesNotMatch(main,/cityTilesReady|drawKenney|city-art\.js|city_tiles\.png/);
assert.ok(!existsSync(join(root,'src/city-art.js')));
assert.ok(!existsSync(join(root,'assets/kenney/city_tiles.png')));
console.log('✓ Original Boston renderer and authoritative geometry retained; accidental tile art absent');
