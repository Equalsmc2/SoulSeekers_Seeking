import assert from 'node:assert/strict';
import {createGame,serialize,spawnEnemy} from '../src/engine.js';
import {networkSnapshot} from '../src/sync.js';
import {newPrediction,predictStep,reconcilePrediction,tweenPosition,receiveEntityMotion} from '../src/prediction.js';
const g=createGame();
const p=g.players[0],start={x:p.x,y:p.y};
const pred=newPrediction(p);
for(let i=0;i<30;i++)predictStep(pred,p,{mx:1,my:0},1/30);
assert.ok(pred.x>start.x+200,'prediction moves locally without server updates');
assert.equal(p.x,start.x,'host authoritative snapshot must remain unchanged');
let remote=new Map();
receiveEntityMotion(remote,[{id:'enemy1',x:100,y:100}],0);
receiveEntityMotion(remote,[{id:'enemy1',x:200,y:100}],160);
const half=tweenPosition(remote.get('enemy1'),240);
assert.ok(half.x>100 && half.x<200,'remote entity smoothly moves between received frames');
assert.deepEqual(tweenPosition(remote.get('enemy1'),500),{x:200,y:100});
const server={...p,x:pred.x+30};
reconcilePrediction(pred,server,true);
assert.ok(pred.x>start.x+200&&pred.x<server.x,'small divergence must correct without snap');
spawnEnemy(g,1,'grunt');
const big=JSON.stringify(serialize(g));
const compact=networkSnapshot(g),small=JSON.stringify(compact);
assert.ok(small.length<big.length*.8,`network state must shrink >=20%: full=${big.length}, lean=${small.length}`);
assert.equal(compact.players.length,6);
assert.equal(compact.enemies.length,g.enemies.length);
assert.equal(compact.players[0].inventory.length,0);
assert.equal(compact.forts.length,6);
assert.ok(!('vx' in (compact.bullets[0]||{})),'network payload omits projectile velocity');
console.log('✓ Prediction is immediate and render-only; remote snapshots interpolate');
console.log(`✓ Network payload ${big.length} → ${small.length} bytes (${Math.round((1-small.length/big.length)*100)}% smaller)`);
