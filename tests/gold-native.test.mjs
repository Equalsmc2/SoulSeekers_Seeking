import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');
const css=readFileSync(join(root,'soulseekers-ui.css'),'utf8');
const html=readFileSync(join(root,'index.html'),'utf8');
const main=readFileSync(join(root,'src/main.js'),'utf8');
assert.match(css,/--ss-gold:#d9b45f/);
assert.match(css,/--ss-gold-bright:#f4d98b/);
assert.match(css,/\.primary,\.online-menu \.primary\{background:var\(--ss-gold\)/);
assert.match(css,/#hpBar\.hp-color\{background:linear-gradient/);
assert.match(html,/R03\.5/);
assert.match(html,/R035/);
assert.match(main,/function drawWorld\(\)/);
assert.doesNotMatch(main,/cityTilesReady|drawKenneyWorld|city-art/);
assert.ok(!existsSync(join(root,'assets/kenney')));
assert.ok(!existsSync(join(root,'src/city-art.js')));
console.log('✓ Gold identity and original non-tiled Boston renderer verified');
