import assert from 'node:assert/strict';
import {makeLatestOnlySender,simulationSteps} from '../src/sync.js';
const ticks=simulationSteps(1);
assert.ok(ticks.count>=15&&ticks.dt<=.055);
assert.ok(Math.abs(ticks.count*ticks.dt-1)<.0001);
let release=()=>{};
const gate=new Promise(resolve=>release=resolve);
const received=[];
const sender=makeLatestOnlySender(async value=>{
  received.push(value);
  if(value===1)await gate;
});
sender.queue(1);
sender.queue(2);
sender.queue(3);
sender.queue(4);
assert.equal(sender.stats().queued,true);
assert.equal(sender.stats().replacements,2);
release();
await new Promise(r=>setTimeout(r,10));
assert.deepEqual(received,[1,4],'stale 2 and 3 must not be sent after latency spike');
assert.equal(sender.stats().busy,false);
let failures=0;
const failing=makeLatestOnlySender(async()=>{throw Error('offline')},()=>failures++);
failing.queue('one');
await new Promise(r=>setTimeout(r,10));
assert.equal(failures,1,'errors must be reported instead of retry flooding');
failing.close();failing.queue('after close');
assert.equal(failing.stats().queued,false);
console.log('✓ Background catch-up simulation step calculation');
console.log('✓ Firebase writes never queue stale snapshots; latest snapshot wins');
console.log('✓ Failed writes report errors without retry storms');
